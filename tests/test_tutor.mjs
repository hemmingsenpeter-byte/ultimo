import assert from "node:assert/strict";
import {fresh,complete} from "../platform/state.mjs";
import {ROLES,grounding,guide,makePrompt,recommendations} from "../platform/tutor.mjs";
const lesson={id:"L01",title:"Retrieval",outcome:"Recall and apply",evidence_criterion:"Explain with an example",reading:["study"],sections:[{title:"Core teaching",body:"Retrieval is reconstructing knowledge without notes."},{title:"Framework",body:"Read then recall then check."},{title:"Worked example",body:"Close your notes before explaining."},{title:"Guided practice",body:"Answer a question from memory."},{title:"Independent transfer",body:"Try another topic."},{title:"Knowledge check",body:"Never include this passage"}],assessment_record:{questions:[{id:"q1",prompt:"What is retrieval?",answer:"Recall without notes."},{id:"q2",prompt:"Why check?",answer:"Correct errors."}]},source_record:{claims:[{source_ids:["study"]}]}};
const c={id:"INT-101",title:"Learning",faculty:"INT",authored:true,prerequisites:[],safety:{notes:"Draft only"},lessons:[lesson]};
const c2={...c,id:"MEN-101",title:"Habits",prerequisites:[c.id]};
const c3={...c,id:"MEN-102",authored:false};
const data={courses:[c,c2,c3],semester:[c.id,c2.id,c3.id],sources:[{id:"study",title:"Study reference"},{id:"other",title:"Unrelated"}]};
const key="INT-101.L01",ctx=grounding(data,key,"retrieval");
assert.equal(ROLES.length,6);
assert.equal(ctx.key,key);
assert.equal(ctx.sources.length,1);
assert.equal(ctx.sources[0].id,"study");
assert.ok(!ctx.sections.some(s=>s.title==="Knowledge check"));
assert.throws(()=>grounding(data,"MEN-102.L01"));
assert.throws(()=>grounding(data,"UNKNOWN.L01"));
assert.ok(guide(ctx,"professor","retrieval").sections[0].text.includes("Retrieval"));
assert.equal(guide(ctx,"examiner","",1).question.id,"q2");
assert.equal(guide(ctx,"socratic","",2).question.id,"q1");
assert.ok(guide(ctx,"coach").sections.some(s=>s.title==="Guided practice"));
assert.ok(guide(ctx,"librarian").message.includes("not independently verified"));
const prompt=makePrompt(ctx,"professor","Explain this");
assert.ok(prompt.includes("[INT-101.L01#Core teaching]"));
assert.ok(prompt.includes("Explain this"));
assert.ok(prompt.includes("Do not invent sources"));
assert.ok(!prompt.includes("Unrelated"));
assert.throws(()=>makePrompt(ctx,"bad","x"));
const state=fresh();
state.hours=1;
assert.deepEqual(recommendations(state,data,"2026-11-26").queue.map(x=>x.key),[key]);
complete(state,key,"2026-11-26");
state.quizzes[key]={correct:1,total:3,date:"2026-11-26"};
const result=recommendations(state,data,"2026-11-27");
assert.equal(result.queue[0].type,"review");
assert.equal(result.queue.filter(x=>x.key===key).length,1);
assert.ok(result.minutes<=result.budget);
assert.equal(result.weakCount,1);
assert.equal(result.completedCourses,1);
assert.equal(recommendations(state,data,"2026-11-26").queue[0].type,"practice");
console.log("Tutor grounding, roles, prompt boundaries and adaptive planner tests passed.");
